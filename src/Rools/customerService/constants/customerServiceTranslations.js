export const translateCustomerServiceText = (value, language) => {
  if (language !== "ar" || typeof value !== "string") return value;
  const trimmed = value.trim();
  if (!trimmed) return value;
  let translated = ARABIC_TEXT[trimmed];
  if (!translated) {
    for (const [pattern, replacement] of ARABIC_PATTERNS) {
      if (pattern.test(trimmed)) { translated = trimmed.replace(pattern, replacement); break; }
    }
  }
  if (!translated) return value;
  return value.replace(trimmed, translated);
};

